"""Write complete FITS files before making them visible at their final path."""

import os
import re
import tempfile
from datetime import UTC
from pathlib import Path
from uuid import uuid4

from astropy.io import fits

from aio_astro import __version__
from aio_astro.domain.models import ImageFrame, MetadataSource, Target
from aio_astro.services.fits_images import image_hdus


class FitsStore:
    def prepare(self, output: Path) -> None:
        output.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryFile(dir=output):
            pass

    def save(self, frame: ImageFrame, output: Path, target: Target | None = None) -> Path:
        output.mkdir(parents=True, exist_ok=True)
        name = re.sub(r"[^A-Za-z0-9_-]+", "_", target.name if target else "Untitled").strip("_")
        name = name[:80] or "Untitled"
        started = frame.started_at.astimezone(UTC)
        stamp = started.strftime("%Y%m%dT%H%M%S_%f")
        destination = output / f"{name}_{frame.exposure.frame_type}_{stamp}_{uuid4().hex[:12]}.fits"
        header = fits.Header()
        header["DATE-OBS"] = (
            started.isoformat(timespec="milliseconds").replace("+00:00", ""),
            "UTC",
        )
        header["TIMESYS"] = "UTC"
        header["EXPTIME"] = (frame.exposure.seconds, "Exposure duration in seconds")
        header["TIMESRC"] = (frame.started_at_source.value, "Source of DATE-OBS")
        header["EXPSRC"] = (frame.duration_source.value, "Source of EXPTIME")
        if frame.started_at_source == MetadataSource.REQUEST:
            header.add_history(
                "DATE-OBS is client UTC at exposure request, not measured sensor start."
            )
        if frame.duration_source == MetadataSource.REQUEST:
            header.add_history(
                "EXPTIME is requested duration; driver did not report actual duration."
            )
        header["IMAGETYP"] = frame.exposure.frame_type.value
        header["OBSPURP"] = (frame.purpose, "SCIENCE, CENTERING or AUTOFOCUS")
        if frame.focus_position is not None:
            header["FOCPOS"] = (frame.focus_position, "Measured focus motor position, steps")
        header["INSTRUME"] = frame.instrument
        header["SWCREATE"] = f"AIO-Astro {__version__}"
        header["SIMULATE"] = (frame.simulated, "Generated by simulated equipment")
        if frame.filter_name is not None:
            header["FILTER"] = (
                frame.filter_name.encode("ascii", errors="replace").decode("ascii"),
                "Filter reported before exposure",
            )
        if frame.camera_settings:
            settings = frame.camera_settings
            for key, value, comment in (
                ("CAMGAIN", settings.gain, "Camera gain setting, driver units/index"),
                ("CAMOFFS", settings.offset, "Camera offset setting, driver units/index"),
                ("XBINNING", settings.bin_x, "Horizontal binning factor"),
                ("YBINNING", settings.bin_y, "Vertical binning factor"),
                ("READMODE", settings.readout, "Driver readout mode"),
                ("CCD-TEMP", settings.temperature_c, "Sensor temperature before exposure, C"),
                ("SET-TEMP", settings.target_c, "Camera cooler target, C"),
                ("COOLER", settings.cooler_on, "Camera cooler enabled before exposure"),
                (
                    "COOLPOWR",
                    settings.cooler_power_percent,
                    "Cooler power before exposure, percent",
                ),
                ("CAMSN", settings.serial_number, "Camera serial number reported by SDK"),
                ("CAMSDK", settings.sdk_version, "Native camera SDK version"),
                ("SWFLIP", settings.restored_sensor_flip, "SDK flip undone: 1=H, 2=V, 3=both"),
            ):
                if value is not None:
                    if isinstance(value, str):
                        value = value.encode("ascii", errors="replace").decode("ascii")
                    header[key] = (value, comment)
        if target:
            # Planned coordinates only; no WCS or telescope pointing is claimed.
            header["OBJECT"] = target.name.encode("ascii", errors="replace").decode("ascii")
            header["OBJRA"] = (target.ra_hours * 15, "Planned target ICRS right ascension, deg")
            header["OBJDEC"] = (target.dec_degrees, "Planned target ICRS declination, deg")
        descriptor, temporary = tempfile.mkstemp(prefix=".aio-", suffix=".fits", dir=output)
        try:
            with os.fdopen(descriptor, "wb") as stream:
                with image_hdus(frame, header) as hdus:
                    hdus.writeto(stream, checksum=True)
                stream.flush()
                os.fsync(stream.fileno())
            # Atomic publication without replacing a pre-existing destination (macOS/Linux).
            os.link(temporary, destination)
        finally:
            Path(temporary).unlink(missing_ok=True)
        return destination
